"""Encrypted blob storage for datasets.

Uploaded CSVs are normalised to Parquet (typed, compressed, fast to scan) and
then encrypted before they touch the disk. Plaintext only exists in memory.
The directory is a shared volume so every API replica can read every blob; in
a cloud deployment swap this class for S3/GCS with server-side KMS as well.
"""
from __future__ import annotations

import io
import os
import threading
import uuid
from collections import OrderedDict
from pathlib import Path

import pyarrow as pa
import pyarrow.parquet as pq

from app.config import get_settings
from app.security import crypto


class BlobStore:
    def __init__(self, root: str) -> None:
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        # Keys are generated by us (uuid hex), but validate anyway: no path traversal.
        if not key.replace("-", "").isalnum():
            raise ValueError("invalid blob key")
        return self.root / f"{key}.bin"

    def put_table(self, table: pa.Table) -> tuple[str, int]:
        buf = io.BytesIO()
        pq.write_table(table, buf, compression="zstd")
        ciphertext = crypto.encrypt(buf.getvalue())
        key = uuid.uuid4().hex
        path = self._path(key)
        tmp = path.with_suffix(".tmp")
        with open(tmp, "wb") as fh:
            fh.write(ciphertext)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)  # atomic on POSIX: readers never see half a file
        return key, len(ciphertext)

    def get_table(self, key: str) -> pa.Table:
        data = crypto.decrypt(self._path(key).read_bytes())
        return pq.read_table(io.BytesIO(data))

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


class TableCache:
    """Bounded LRU of decrypted tables, so repeated questions skip decrypt+parse.

    Bounded by total bytes, not entries, so one huge file cannot pin all memory."""

    def __init__(self, max_bytes: int = 512 * 1024 * 1024) -> None:
        self._items: OrderedDict[str, pa.Table] = OrderedDict()
        self._bytes = 0
        self._max = max_bytes
        self._lock = threading.Lock()

    def get(self, key: str) -> pa.Table | None:
        with self._lock:
            table = self._items.get(key)
            if table is not None:
                self._items.move_to_end(key)
            return table

    def put(self, key: str, table: pa.Table) -> None:
        size = table.nbytes
        if size > self._max:
            return
        with self._lock:
            if key in self._items:
                return
            self._items[key] = table
            self._bytes += size
            while self._bytes > self._max:
                _, evicted = self._items.popitem(last=False)
                self._bytes -= evicted.nbytes

    def drop(self, key: str) -> None:
        with self._lock:
            table = self._items.pop(key, None)
            if table is not None:
                self._bytes -= table.nbytes


_store: BlobStore | None = None
table_cache = TableCache()


def get_store() -> BlobStore:
    global _store
    if _store is None:
        _store = BlobStore(get_settings().storage_dir)
    return _store


def load_table(blob_key: str) -> pa.Table:
    cached = table_cache.get(blob_key)
    if cached is not None:
        return cached
    table = get_store().get_table(blob_key)
    table_cache.put(blob_key, table)
    return table
